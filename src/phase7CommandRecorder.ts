export interface Phase7CommandRecorderInput {
  outputPath: string;
  force?: boolean;
  includeHosted?: boolean;
  includePreflight?: boolean;
  evidenceEnvFile?: string;
  evidenceDirectory?: string;
  proofPath?: string;
  seedOutputPath?: string;
  exists: (path: string) => boolean;
  runCommand: (
    file: string,
    args: readonly string[],
  ) => Phase7RecordedCommandResult;
  sleep?: (milliseconds: number) => void;
  writeText: (path: string, text: string) => void;
  now?: () => Date;
}

export interface Phase7RecordedCommandResult {
  exitCode: number;
  stdout: string;
  stderr: string;
}

export interface Phase7CommandRecorderReport {
  schema: "split402.phase7_command_recorder.v1";
  ok: boolean;
  outputPath: string;
  commandCount: number;
  failedCommands: string[];
  written: boolean;
  nextActions: string[];
}

interface CommandSpec {
  command: string;
  file: string;
  args: readonly string[];
  outputPath?: string;
  retry?: {
    attempts: number;
    delayMs: number;
  };
}

