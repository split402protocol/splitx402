export function recordPhase7LocalCommandEvidence(
  input: Phase7CommandRecorderInput,
): Phase7CommandRecorderReport {
  if (input.exists(input.outputPath) && input.force !== true) {
    return {
      schema: "split402.phase7_command_recorder.v1",
      ok: false,
      outputPath: input.outputPath,
      commandCount: 0,
      failedCommands: [],
      written: false,
      nextActions: [
        `Refusing to overwrite ${input.outputPath}; pass --force only after saving any real hosted transcript content.`,
      ],
    };
  }

  const hostedCommands =
    input.includeHosted === true ? createHostedStagingCommands(input) : [];
  const commands = [
    ...(input.includePreflight === true || input.includeHosted === true
      ? [preflightCommand]
      : []),
    ...hostedCommands,
    ...safeLocalCommands,
  ];
  const blocks: string[] = [
    "# Split402 Phase 7 command evidence transcript",
    "#",
    "# Generated by corepack pnpm phase7:staging:commands-record.",
    input.includeHosted === true
      ? "# This includes hosted staging commands from this runtime."
      : "# This records safe local validation commands only. Add hosted Docker, seed,",
    ...(input.includeHosted === true
      ? [
          "# It must be run only after private hosted env values are filled.",
          "# Do not commit this transcript; keep it in the private evidence workspace.",
        ]
      : [
          "# collection, paid-suite, manifest, assemble, and status command blocks from",
          "# the real hosted staging run before final Phase 7 approval.",
        ]),
    `# generated_at: ${(input.now ?? (() => new Date()))().toISOString()}`,
    "",
  ];
  const failedCommands: string[] = [];

  for (const command of commands) {
    const result = runCommandWithRetry(input, command);
    if (
      command.outputPath !== undefined &&
      result.exitCode === 0 &&
      result.stdout.length > 0
    ) {
      input.writeText(command.outputPath, result.stdout);
    }
    blocks.push(formatCommandBlock(command.command, result));
    if (result.exitCode !== 0) {
      failedCommands.push(command.command);
    }
  }

  const text = `${blocks.join("\n")}\n`;
  input.writeText(input.outputPath, text);

  return {
    schema: "split402.phase7_command_recorder.v1",
    ok: failedCommands.length === 0,
    outputPath: input.outputPath,
    commandCount: commands.length,
    failedCommands,
    written: true,
    nextActions: createNextActions(input.outputPath, failedCommands),
  };
}

function runCommandWithRetry(
  input: Phase7CommandRecorderInput,
  command: CommandSpec,
): Phase7RecordedCommandResult {
  const attempts = command.retry?.attempts ?? 1;
  let result: Phase7RecordedCommandResult | undefined;

  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    result = input.runCommand(command.file, command.args);
    if (result.exitCode === 0 || attempt === attempts) {
      return result;
    }
    input.sleep?.(command.retry?.delayMs ?? 0);
  }

  return result ?? { exitCode: 1, stdout: "", stderr: "" };
}

function formatCommandBlock(
  command: string,
  result: Phase7RecordedCommandResult,
): string {
  return [
    `$ ${command}`,
    redactSensitiveCommandOutput(result.stdout).trimEnd(),
    redactSensitiveCommandOutput(result.stderr).trimEnd(),
    result.exitCode === 0 ? "" : `# exit_code: ${result.exitCode}`,
    "",
  ]
    .filter((line, index) => index === 0 || line.length > 0)
    .join("\n");
}

